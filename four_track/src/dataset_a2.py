"""Track A2 datasets: pseudo-label loader + train/pseudo mixed sampler.

Two pieces:

  - `SoundscapePseudoDataset` — loads 5-sec chunks from
    `data/raw/train_soundscapes/`, paired with per-class soft labels from
    the filtered NPZ produced by `src/a2_filter_pseudo.py`. Returns the
    same `(mel, labels, sec_mask)` triple as `BirdTrainDatasetA1` so it
    drops into the existing training loop unchanged.
    The fold filter (`fold_filter=k`) restricts to pseudo rows whose
    `oof_bucket == k`. This implements Sydorskyi's OOF safety: when fold
    k's model trains, it never sees pseudo-labels generated by itself.

  - `MixedTrainPseudoDataset` — length-aligned to the train side; per
    `__getitem__`, with probability `pseudo_ratio` returns a random pseudo
    item, else returns the train item at the given index. This implements
    Sydorskyi's 40% pseudo / 60% train sampling rule (approximately —
    his exact rule is conditional on per-class pseudo coverage, but the
    flat 40/60 captures the dominant effect; see new_plan.md §14.17.5).

Pseudo items skip the train MixUp path (the 234-class soft label already
encodes multi-species presence). Train items keep the existing
train×train MixUp inside `BirdTrainDataset`. Future iter could add
cross-mixup (train hard × pseudo soft via element-wise sum + clip per
Sydorskyi §5.4); deferred to keep iter-1 simple.
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset

HERE       = Path(__file__).resolve().parent
FT_ROOT    = HERE.parent
ROOT       = FT_ROOT.parent
PARENT_SRC = ROOT / "src"

if str(PARENT_SRC) not in sys.path:
    sys.path.insert(0, str(PARENT_SRC))
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import config  # noqa: E402
from config import (  # noqa: E402
    RAW, SAMPLE_RATE, CHUNK_SAMPLES,
    GAIN_PROB, GAIN_DB_RANGE, TIME_SHIFT_PROB,
)
from utils import load_audio, pad_or_crop, waveform_to_mel  # noqa: E402

WINDOW_SEC = 5


class SoundscapePseudoDataset(Dataset):
    """Per-(file, start_sec) pseudo-labelled chunk dataset.

    Args:
        npz_path : path to a2_pseudo_soft.npz (from a2_filter_pseudo.py)
        fold_filter : if given, keep only rows where oof_bucket == fold_filter
        augment : apply gain + time-shift augmentations (default True)
        cap_k : if > 0, per top-1-species cap on pseudo rows = cap_k * train_per_class[c].
                Applied globally before fold_filter so all folds see the same
                cap-restricted substrate, just partitioned by oof_bucket.
                Addresses the §14.17.10 mass-augmentation drift (1284×
                aug_factor for tail species). Requires train_per_class.
        train_per_class : np.ndarray (N_CLASSES,) of focal-clip counts per
                class index (global, across all folds). Used only if cap_k > 0.
        cap_seed : RNG seed for the per-class subsample (deterministic across
                folds). Default 42.
    """

    def __init__(
        self,
        npz_path: Path | str,
        fold_filter: int | None = None,
        augment: bool = True,
        cap_k: int = 0,
        train_per_class: np.ndarray | None = None,
        cap_seed: int = 42,
    ):
        npz_path = Path(npz_path)
        if not npz_path.exists():
            raise FileNotFoundError(
                f"pseudo NPZ not found: {npz_path}\n"
                f"Run src/a2_filter_pseudo.py first."
            )
        z = np.load(npz_path, allow_pickle=False)
        files    = z["filenames"].astype(str)
        starts   = z["start_sec"].astype(np.int32)
        buckets  = z["oof_bucket"].astype(np.int8)
        soft     = z["soft_labels"].astype(np.float32)
        n_classes = config.N_CLASSES
        assert soft.shape[1] == n_classes, (
            f"pseudo NPZ has {soft.shape[1]} classes, expected {n_classes}"
        )

        if cap_k > 0:
            if train_per_class is None or len(train_per_class) != n_classes:
                raise ValueError(
                    f"cap_k>0 requires train_per_class of shape ({n_classes},); "
                    f"got {None if train_per_class is None else train_per_class.shape}"
                )
            n_before = len(soft)
            top1 = soft.argmax(axis=1)
            keep_mask = np.zeros(n_before, dtype=bool)
            rng = np.random.default_rng(cap_seed)
            for c in np.unique(top1):
                idxs = np.where(top1 == c)[0]
                cap = cap_k * max(int(train_per_class[c]), 1)
                if len(idxs) > cap:
                    chosen = rng.choice(idxs, size=cap, replace=False)
                    keep_mask[chosen] = True
                else:
                    keep_mask[idxs] = True
            files, starts, buckets, soft = (
                files[keep_mask], starts[keep_mask], buckets[keep_mask], soft[keep_mask]
            )
            n_after = len(soft)
            print(
                f"  pseudo cap_k={cap_k}: kept {n_after:,} of {n_before:,} "
                f"({100*n_after/n_before:.1f}%) — aug_factor ≤ {cap_k} per class",
                flush=True,
            )

        if fold_filter is not None:
            keep = (buckets == int(fold_filter))
            files, starts, buckets, soft = (
                files[keep], starts[keep], buckets[keep], soft[keep]
            )

        self.files     = files
        self.starts    = starts
        self.buckets   = buckets
        self.soft      = soft
        self.augment   = augment
        self.n_classes = n_classes

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, idx: int):
        path = RAW / "train_soundscapes" / str(self.files[idx])
        try:
            full = load_audio(path)
        except Exception:
            full = np.zeros(SAMPLE_RATE * 60, dtype=np.float32)

        s = int(self.starts[idx]) * SAMPLE_RATE
        e = s + WINDOW_SEC * SAMPLE_RATE
        seg = full[s:e] if e <= len(full) else full[s:]
        # pad_or_crop with random_crop=False front-crops; for a 5s segment
        # this tiles to 20s (CHUNK_SAMPLES). Matches the OOF-emit convention.
        wav = pad_or_crop(seg, CHUNK_SAMPLES, random_crop=False)

        if self.augment:
            if random.random() < GAIN_PROB:
                db  = random.uniform(-GAIN_DB_RANGE, GAIN_DB_RANGE)
                wav = wav * (10.0 ** (db / 20.0))
            if random.random() < TIME_SHIFT_PROB:
                max_shift = int(0.25 * len(wav))
                shift = random.randint(-max_shift, max_shift)
                wav = np.roll(wav, shift)

        mel    = waveform_to_mel(wav.astype(np.float32, copy=False))
        labels = torch.from_numpy(self.soft[idx])
        mask   = torch.ones(self.n_classes, dtype=torch.float32)
        return mel, labels, mask


class MixedTrainPseudoDataset(Dataset):
    """40% pseudo / 60% train sampler.

    Length is fixed to len(train_ds); per __getitem__, with probability
    `pseudo_ratio` (default 0.4) we return a uniformly random pseudo
    item, else the train item at idx. This means each training epoch
    sees ~60% of train_ds and ~0.4*len(train_ds) random pseudo draws —
    consistent with Sydorskyi's per-step pseudo bias.

    If `pseudo_ds` is empty (fold has no kept pseudos), returns the
    train item unconditionally.
    """

    def __init__(
        self,
        train_ds: Dataset,
        pseudo_ds: SoundscapePseudoDataset,
        pseudo_ratio: float = 0.4,
    ):
        self.train_ds     = train_ds
        self.pseudo_ds    = pseudo_ds
        self.pseudo_ratio = float(pseudo_ratio)
        self.n_pseudo     = len(pseudo_ds)

    def __len__(self) -> int:
        return len(self.train_ds)

    def __getitem__(self, idx: int):
        if self.n_pseudo > 0 and random.random() < self.pseudo_ratio:
            j = random.randint(0, self.n_pseudo - 1)
            return self.pseudo_ds[j]
        return self.train_ds[idx]
