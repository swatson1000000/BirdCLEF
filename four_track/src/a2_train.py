"""src/a2_train.py — Track A2 step 4: A1 + iterative noisy-student retrain.

Trains the four_track A2 branch by mixing the existing A1 focal-clip pipeline
with the OOF pseudo-labels from `data/processed/a2_pseudo_soft.npz`.
Sampling rule: per training step, with `--pseudo-ratio` probability draw a
random pseudo chunk; else draw the indexed train clip. Each fold's pseudo
pool is filtered to `oof_bucket == fold` so fold k never trains on a
pseudo-label generated by itself (Sydorskyi OOF safety, see new_plan.md
§14.17).

Differences vs `train_a1.py`:
  - Wraps `BirdTrainDatasetA1` in `MixedTrainPseudoDataset`
  - New args: `--pseudo-npz`, `--pseudo-ratio`
  - Saves checkpoints under `four_track/models/a2/` (a1 ckpts untouched)
  - Default loss = hybrid (matches v62 baseline; soft labels supported by
    BCE + ASL terms natively — see losses.py)

Recipe is iter-1 of the §14.17.5 Track-A2 plan: pseudo + train mixed
without cross-mixup; if iter-1 lifts LB we add cross-mixup in iter-2.

Note: an older `train_a2.py` exists in this repo for a different approach
(GT-anchor-only soundscape supervision via SoundscapeTrainDataset). This
file is the §14.17 noisy-student version and is intentionally a sibling
file, not a replacement.

Usage:
    # Single fold smoke (1 ep, 1 batch, 1 val batch)
    python -u src/a2_train.py --fold 0 --smoke-test

    # All five folds, 25 ep each, default 0.4 pseudo ratio
    python -u src/a2_train.py --folds 0,1,2,3,4 --loss hybrid

    # Skip pseudo for a controlled A1-baseline parity run
    python -u src/a2_train.py --folds 0,1,2,3,4 --pseudo-ratio 0.0
"""

